#include <Core/Platform/Shared/Process/SIRPlatformPipe.h>

#include <cstddef>
#include <cstdint>
#include <errno.h>
#include <fcntl.h>
#include <limits.h>
#include <pthread.h>
#include <signal.h>
#include <time.h>
#include <unistd.h>

// Keep SIGPIPE blocked only on this writer thread. Consume only the SIGPIPE
// generated by this failed write, not one already pending for this thread.
static ssize_t sirPipeWriteNoSigpipe( int nHandle, const void *pData, size_t nBytes, int *pError ) noexcept
{
	sigset_t blocked{};
	sigset_t original{};
	sigemptyset( &blocked );
	sigaddset( &blocked, SIGPIPE );

	if ( pthread_sigmask( SIG_BLOCK, &blocked, &original ) != 0 ) {
		*pError = EINVAL;
		return -1;
	}

	sigset_t pendingBefore{};
	const bool bHadPending = sigpending( &pendingBefore ) == 0 && sigismember( &pendingBefore, SIGPIPE ) == 1;
	const ssize_t nResult = ::write( nHandle, pData, nBytes );
	const int nError = nResult < 0 ? errno : 0;
	if ( nError == EPIPE && !bHadPending ) {
		struct timespec timeout{};
		static_cast<void>(sigtimedwait( &blocked, nullptr, &timeout ));
	}
	const int nRestore = pthread_sigmask( SIG_SETMASK, &original, nullptr );

	*pError = nRestore == 0 ? nError : EINVAL;
	return nRestore == 0 ? nResult : -1;
}

SIRPlatformPipe::SIRPlatformPipe( void ) noexcept : m_nReadHandle( UINTPTR_MAX ), m_nWriteHandle( UINTPTR_MAX )
{
}

SIRPlatformPipe::SIRPlatformPipe( SIRPlatformPipe&& other ) noexcept
    : m_nReadHandle( other.m_nReadHandle ), m_nWriteHandle( other.m_nWriteHandle )
{
	other.m_nReadHandle = UINTPTR_MAX;
	other.m_nWriteHandle = UINTPTR_MAX;
}

SIRPlatformPipe::~SIRPlatformPipe( void ) noexcept
{
	static_cast<void>( close() );
}

sirPipeResult SIRPlatformPipe::create( void ) noexcept
{
	if ( isReadOpen() || isWriteOpen() ) {
		return sirPipeResult::SIR_PIPE_INVALID_ARGUMENT;
	}
	int szHandles[2] = { -1, -1 };
#if defined( __linux__ )
	if ( pipe2( szHandles, O_CLOEXEC ) != 0 ) {
		return sirPipeResult::SIR_PIPE_IO_ERROR;
	}
#else
	if ( pipe( szHandles ) != 0 ) {
		return sirPipeResult::SIR_PIPE_IO_ERROR;
	}
#endif
	m_nReadHandle = static_cast<uintptr_t>( szHandles[0] );
	m_nWriteHandle = static_cast<uintptr_t>( szHandles[1] );
	return sirPipeResult::SIR_PIPE_OK;
}

sirPipeResult SIRPlatformPipe::read( void *pDestination, uint64_t nBytes, uint64_t *pTransferred ) noexcept
{
	if ( pTransferred == nullptr ) {
		return sirPipeResult::SIR_PIPE_INVALID_ARGUMENT;
	}

	*pTransferred = 0;
	if ( !isReadOpen() ) {
		return sirPipeResult::SIR_PIPE_CLOSED;
	}
	if ( nBytes != 0 && pDestination == nullptr ) {
		return sirPipeResult::SIR_PIPE_INVALID_ARGUMENT;
	}
	if ( nBytes == 0 ) {
		return sirPipeResult::SIR_PIPE_OK;
	}

	constexpr const size_t MB = static_cast<size_t>( 1024 * 1024 );
	const size_t nStep = static_cast<size_t>( nBytes < MB ? nBytes : MB );
	for ( ;; ) {
		const ssize_t nRead = ::read( static_cast<int>( m_nReadHandle ), pDestination, nStep );
		if ( nRead < 0 && errno == EINTR ) {
			continue;
		}
		if ( nRead < 0 ) {
			return sirPipeResult::SIR_PIPE_IO_ERROR;
		}
		if ( nRead == 0 ) {
			return sirPipeResult::SIR_PIPE_END_OF_STREAM;
		}
		*pTransferred = static_cast<uint64_t>( nRead );
		return sirPipeResult::SIR_PIPE_OK;
	}
}

sirPipeResult SIRPlatformPipe::write( const void *pSource, uint64_t nBytes, uint64_t *pTransferred ) noexcept
{
	if ( pTransferred == nullptr ) {
		return sirPipeResult::SIR_PIPE_INVALID_ARGUMENT;
	}

	*pTransferred = 0;
	if ( !isWriteOpen() ) {
		return sirPipeResult::SIR_PIPE_CLOSED;
	}
	if ( nBytes != 0 && pSource == nullptr ) {
		return sirPipeResult::SIR_PIPE_INVALID_ARGUMENT;
	}
	while ( *pTransferred < nBytes ) {
		const uint64_t nLeft = nBytes - *pTransferred;
		const size_t nStep = static_cast<size_t>( nLeft < 64 * 1024 ? nLeft : 64 * 1024 );
		int nError = 0;

		const ssize_t nWritten = sirPipeWriteNoSigpipe( static_cast<int>( m_nWriteHandle ), reinterpret_cast<const uint8_t *>( pSource ) + *pTransferred, nStep, &nError );
		if ( nWritten < 0 && nError == EINTR ) {
			continue;
		}
		if ( nWritten < 0 ) {
			return nError == EPIPE ? sirPipeResult::SIR_PIPE_BROKEN : sirPipeResult::SIR_PIPE_IO_ERROR;
		}
		if ( nWritten == 0 ) {
			return sirPipeResult::SIR_PIPE_IO_ERROR;
		}
		*pTransferred += static_cast<uint64_t>( nWritten );
	}
	return sirPipeResult::SIR_PIPE_OK;
}

sirPipeResult SIRPlatformPipe::closeRead( void ) noexcept
{
	if ( !isReadOpen() ) {
		return sirPipeResult::SIR_PIPE_OK;
	}
	const int nHandle = static_cast<int>( m_nReadHandle );
	m_nReadHandle = UINTPTR_MAX;
	return ::close( nHandle ) == 0 ? sirPipeResult::SIR_PIPE_OK : sirPipeResult::SIR_PIPE_IO_ERROR;
}

sirPipeResult SIRPlatformPipe::closeWrite( void ) noexcept
{
	if ( !isWriteOpen() ) {
		return sirPipeResult::SIR_PIPE_OK;
	}
	const int nHandle = static_cast<int>( m_nWriteHandle );
	m_nWriteHandle = UINTPTR_MAX;
	return ::close( nHandle ) == 0 ? sirPipeResult::SIR_PIPE_OK : sirPipeResult::SIR_PIPE_IO_ERROR;
}

sirPipeResult SIRPlatformPipe::close( void ) noexcept
{
	const sirPipeResult eRead = closeRead();
	const sirPipeResult eWrite = closeWrite();
	return eRead != sirPipeResult::SIR_PIPE_OK ? eRead : eWrite;
}

bool SIRPlatformPipe::isReadOpen( void ) const noexcept
{
	return m_nReadHandle != UINTPTR_MAX;
}

bool SIRPlatformPipe::isWriteOpen( void ) const noexcept
{
	return m_nWriteHandle != UINTPTR_MAX;
}

#include <Core/Platform/SIRPlatformPipe.h>

#include <errno.h>
#include <fcntl.h>
#include <limits.h>
#include <pthread.h>
#include <signal.h>
#include <time.h>
#include <unistd.h>

// Keep SIGPIPE blocked only on this writer thread. Consume only the SIGPIPE
// generated by this failed write, not one already pending for this thread.
static ssize_t sirPipeWriteNoSigpipe( int nHandle, const void *pData, size_t nBytes, int *pError ) noexcept
{
	sigset_t blocked = {};
	sigset_t original = {};
	sigemptyset( &blocked );
	sigaddset( &blocked, SIGPIPE );
	if ( pthread_sigmask( SIG_BLOCK, &blocked, &original ) != 0 ) {
		*pError = EINVAL;
		return -1;
	}
	sigset_t pendingBefore = {};
	const bool bHadPending = sigpending( &pendingBefore ) == 0 && sigismember( &pendingBefore, SIGPIPE ) == 1;
	const ssize_t nResult = ::write( nHandle, pData, nBytes );
	const int nError = nResult < 0 ? errno : 0;
	if ( nError == EPIPE && !bHadPending ) {
		struct timespec timeout = {};
		( void )sigtimedwait( &blocked, nullptr, &timeout );
	}
	const int nRestore = pthread_sigmask( SIG_SETMASK, &original, nullptr );
	*pError = nRestore == 0 ? nError : EINVAL;
	return nRestore == 0 ? nResult : -1;
}

SIRPlatformPipe::SIRPlatformPipe( void ) noexcept : m_nReadHandle( UINTPTR_MAX ), m_nWriteHandle( UINTPTR_MAX )
{
}

SIRPlatformPipe::~SIRPlatformPipe( void ) noexcept
{
	close();
}

sirPipeResult_t SIRPlatformPipe::create( void ) noexcept
{
	if ( isReadOpen() || isWriteOpen() ) {
		return SIR_PIPE_INVALID_ARGUMENT;
	}
	int szHandles[2] = { -1, -1 };
#if defined( __linux__ )
	if ( pipe2( szHandles, O_CLOEXEC ) != 0 ) {
		return SIR_PIPE_IO_ERROR;
	}
#else
	if ( pipe( szHandles ) != 0 ) {
		return SIR_PIPE_IO_ERROR;
	}
#endif
	m_nReadHandle = ( uintptr_t )szHandles[0];
	m_nWriteHandle = ( uintptr_t )szHandles[1];
	return SIR_PIPE_OK;
}

sirPipeResult_t SIRPlatformPipe::read( void *pDestination, uint64_t nBytes, uint64_t *pTransferred ) noexcept
{
	if ( pTransferred == nullptr ) {
		return SIR_PIPE_INVALID_ARGUMENT;
	}
	*pTransferred = 0;
	if ( !isReadOpen() ) {
		return SIR_PIPE_CLOSED;
	}
	if ( nBytes != 0 && pDestination == nullptr ) {
		return SIR_PIPE_INVALID_ARGUMENT;
	}
	if ( nBytes == 0 ) {
		return SIR_PIPE_OK;
	}
	const size_t nStep = ( size_t )( nBytes < 1024 * 1024 ? nBytes : 1024 * 1024 );
	for ( ;; ) {
		const ssize_t nRead = ::read( ( int )m_nReadHandle, pDestination, nStep );
		if ( nRead < 0 && errno == EINTR ) {
			continue;
		}
		if ( nRead < 0 ) {
			return SIR_PIPE_IO_ERROR;
		}
		if ( nRead == 0 ) {
			return SIR_PIPE_END_OF_STREAM;
		}
		*pTransferred = ( uint64_t )nRead;
		return SIR_PIPE_OK;
	}
}

sirPipeResult_t SIRPlatformPipe::write( const void *pSource, uint64_t nBytes, uint64_t *pTransferred ) noexcept
{
	if ( pTransferred == nullptr ) {
		return SIR_PIPE_INVALID_ARGUMENT;
	}
	*pTransferred = 0;
	if ( !isWriteOpen() ) {
		return SIR_PIPE_CLOSED;
	}
	if ( nBytes != 0 && pSource == nullptr ) {
		return SIR_PIPE_INVALID_ARGUMENT;
	}
	while ( *pTransferred < nBytes ) {
		const uint64_t nLeft = nBytes - *pTransferred;
		const size_t nStep = ( size_t )( nLeft < 64 * 1024 ? nLeft : 64 * 1024 );
		int nError = 0;
		const ssize_t nWritten = sirPipeWriteNoSigpipe( ( int )m_nWriteHandle, ( const uint8_t * )pSource + *pTransferred, nStep, &nError );
		if ( nWritten < 0 && nError == EINTR ) {
			continue;
		}
		if ( nWritten < 0 ) {
			return nError == EPIPE ? SIR_PIPE_BROKEN : SIR_PIPE_IO_ERROR;
		}
		if ( nWritten == 0 ) {
			return SIR_PIPE_IO_ERROR;
		}
		*pTransferred += ( uint64_t )nWritten;
	}
	return SIR_PIPE_OK;
}

sirPipeResult_t SIRPlatformPipe::closeRead( void ) noexcept
{
	if ( !isReadOpen() ) {
		return SIR_PIPE_OK;
	}
	const int nHandle = ( int )m_nReadHandle;
	m_nReadHandle = UINTPTR_MAX;
	return ::close( nHandle ) == 0 ? SIR_PIPE_OK : SIR_PIPE_IO_ERROR;
}

sirPipeResult_t SIRPlatformPipe::closeWrite( void ) noexcept
{
	if ( !isWriteOpen() ) {
		return SIR_PIPE_OK;
	}
	const int nHandle = ( int )m_nWriteHandle;
	m_nWriteHandle = UINTPTR_MAX;
	return ::close( nHandle ) == 0 ? SIR_PIPE_OK : SIR_PIPE_IO_ERROR;
}

sirPipeResult_t SIRPlatformPipe::close( void ) noexcept
{
	const sirPipeResult_t eRead = closeRead();
	const sirPipeResult_t eWrite = closeWrite();
	return eRead != SIR_PIPE_OK ? eRead : eWrite;
}

bool SIRPlatformPipe::isReadOpen( void ) const noexcept
{
	return m_nReadHandle != UINTPTR_MAX;
}

bool SIRPlatformPipe::isWriteOpen( void ) const noexcept
{
	return m_nWriteHandle != UINTPTR_MAX;
}

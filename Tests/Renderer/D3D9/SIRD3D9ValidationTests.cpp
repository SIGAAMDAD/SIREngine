#include <Renderer/Drivers/D3D9/SIRD3D9Validation.h>
#include <assert.h>

int main( void )
{
	assert( sirD3D9ValidateBufferWrite( 128, 0, 64, 4 ) == SIR_GRAPHICS_SUCCESS );
	assert( sirD3D9ValidateBufferWrite( 128, 64, 64, 4 ) == SIR_GRAPHICS_SUCCESS );
	assert( sirD3D9ValidateBufferWrite( 128, 128, 1, 1 ) == SIR_GRAPHICS_INVALID_ARGUMENT );
	assert( sirD3D9ValidateBufferWrite( 128, UINT32_MAX, 8, 4 ) == SIR_GRAPHICS_INVALID_ARGUMENT );
	assert( sirD3D9ValidateBufferWrite( 128, 1, 8, 4 ) == SIR_GRAPHICS_INVALID_ARGUMENT );
	assert( sirD3D9ValidateBufferWrite( 128, 4, 7, 4 ) == SIR_GRAPHICS_INVALID_ARGUMENT );
	assert( sirD3D9ValidateBufferWrite( 128, 4, 8, 3 ) == SIR_GRAPHICS_INVALID_ARGUMENT );
	assert( sirD3D9ValidateBufferWrite( 128, 0, 0, 1 ) == SIR_GRAPHICS_INVALID_ARGUMENT );
	assert( sirD3D9ValidateBufferWrite( 0, 0, 1, 1 ) == SIR_GRAPHICS_INVALID_ARGUMENT );

	const uint32_t szVertex[] = { 0xfffe0300U, 0x0000ffffU };
	const uint32_t szPixel[] = { 0xffff0200U, 0x0000ffffU };
	assert( sirD3D9ValidateShaderTokens( szVertex, sizeof( szVertex ), SIR_GRAPHICS_STAGE_VERTEX, 0x0300 ) == SIR_GRAPHICS_SUCCESS );
	assert( sirD3D9ValidateShaderTokens( szVertex, sizeof( szVertex ), SIR_GRAPHICS_STAGE_FRAGMENT, 0x0300 ) == SIR_GRAPHICS_UNSUPPORTED );
	assert( sirD3D9ValidateShaderTokens( szVertex, sizeof( szVertex ), SIR_GRAPHICS_STAGE_VERTEX, 0x0200 ) == SIR_GRAPHICS_UNSUPPORTED );
	assert( sirD3D9ValidateShaderTokens( szPixel, sizeof( szPixel ), SIR_GRAPHICS_STAGE_FRAGMENT, 0x0300 ) == SIR_GRAPHICS_SUCCESS );
	assert( sirD3D9ValidateShaderTokens( nullptr, 8, SIR_GRAPHICS_STAGE_VERTEX, 0x0300 ) == SIR_GRAPHICS_INVALID_ARGUMENT );
	assert( sirD3D9ValidateShaderTokens( szVertex, 7, SIR_GRAPHICS_STAGE_VERTEX, 0x0300 ) == SIR_GRAPHICS_INVALID_ARGUMENT );
	float aFloatRegisters[8] = {};
	int32_t aIntegerRegisters[4] = {};
	sirD3D9ShaderConstants_t constants = {};
	constants.nStage = SIR_GRAPHICS_STAGE_VERTEX;
	constants.nFirstRegister = 254;
	constants.nRegisterCount = 2;
	constants.pFloat4 = aFloatRegisters;
	assert( sirD3D9ValidateShaderConstants( &constants, 0x0300, 256 ) == SIR_GRAPHICS_SUCCESS );
	constants.nFirstRegister = 255;
	assert( sirD3D9ValidateShaderConstants( &constants, 0x0300, 256 ) == SIR_GRAPHICS_UNSUPPORTED );
	constants.nFirstRegister = 0;
	constants.nStage = SIR_GRAPHICS_STAGE_FRAGMENT;
	constants.nRegisterCount = 224;
	assert( sirD3D9ValidateShaderConstants( &constants, 0x0300, 256 ) == SIR_GRAPHICS_SUCCESS );
	assert( sirD3D9ValidateShaderConstants( &constants, 0x0200, 256 ) == SIR_GRAPHICS_UNSUPPORTED );
	constants.nRegisterCount = 32;
	assert( sirD3D9ValidateShaderConstants( &constants, 0x0200, 256 ) == SIR_GRAPHICS_SUCCESS );
	constants.nRegisterCount = 1;
	constants.pInt4 = aIntegerRegisters;
	assert( sirD3D9ValidateShaderConstants( &constants, 0x0300, 256 ) == SIR_GRAPHICS_INVALID_ARGUMENT );
	constants.pFloat4 = nullptr;
	constants.nFirstRegister = 15;
	assert( sirD3D9ValidateShaderConstants( &constants, 0x0300, 256 ) == SIR_GRAPHICS_SUCCESS );
	constants.nFirstRegister = 16;
	assert( sirD3D9ValidateShaderConstants( &constants, 0x0300, 256 ) == SIR_GRAPHICS_UNSUPPORTED );
	constants.nStage = SIR_GRAPHICS_STAGE_COMPUTE;
	assert( sirD3D9ValidateShaderConstants( &constants, 0x0300, 256 ) == SIR_GRAPHICS_INVALID_ARGUMENT );
	constants.nStage = SIR_GRAPHICS_STAGE_VERTEX;
	constants.nFirstRegister = 0;
	constants.nRegisterCount = 0;
	assert( sirD3D9ValidateShaderConstants( &constants, 0x0300, 256 ) == SIR_GRAPHICS_INVALID_ARGUMENT );
	sirGraphicsBufferDesc_t buffer = {};
	buffer.nSizeBytes = 512;
	buffer.nAlignmentBytes = 16;
	buffer.nUsage = SIR_GRAPHICS_USAGE_VERTEX;
	buffer.eMemory = SIR_GRAPHICS_MEMORY_CPU_UPLOAD;
	assert( sirD3D9ValidateBuffer( &buffer ) == SIR_GRAPHICS_SUCCESS );
	buffer.nUsage = SIR_GRAPHICS_USAGE_STORAGE;
	assert( sirD3D9ValidateBuffer( &buffer ) == SIR_GRAPHICS_UNSUPPORTED );
	buffer.nUsage = SIR_GRAPHICS_USAGE_VERTEX;
	buffer.nSizeBytes = UINT64_MAX;
	assert( sirD3D9ValidateBuffer( &buffer ) == SIR_GRAPHICS_INVALID_ARGUMENT );
	sirGraphicsTextureDesc_t texture = {};
	texture.nWidth = 256;
	texture.nHeight = 256;
	texture.nDepth = 1;
	texture.nArrayLayers = 1;
	texture.nMipLevels = 1;
	texture.nSampleCount = 1;
	texture.nUsage = SIR_GRAPHICS_USAGE_SAMPLED;
	texture.eDimension = SIR_GRAPHICS_TEXTURE_2D;
	texture.eFormat = SIR_GRAPHICS_FORMAT_BGRA8_UNORM;
	texture.eMemory = SIR_GRAPHICS_MEMORY_GPU_LOCAL;
	assert( sirD3D9ValidateTexture( &texture, 2048, 4 ) == SIR_GRAPHICS_SUCCESS );
	texture.eFormat = SIR_GRAPHICS_FORMAT_BC7_UNORM;
	assert( sirD3D9ValidateTexture( &texture, 2048, 4 ) == SIR_GRAPHICS_UNSUPPORTED );
	texture.eFormat = SIR_GRAPHICS_FORMAT_BGRA8_UNORM;
	texture.nSampleCount = 4;
	assert( sirD3D9ValidateTexture( &texture, 2048, 4 ) == SIR_GRAPHICS_UNSUPPORTED );
	texture.nWidth = 4096;
	assert( sirD3D9ValidateTexture( &texture, 2048, 4 ) == SIR_GRAPHICS_INVALID_ARGUMENT );
	texture.nWidth = 256;
	texture.nSampleCount = 1;
	uint64_t nTextureBytes = 0;
	assert( sirD3D9EstimateTextureBytes( &texture, &nTextureBytes ) == SIR_GRAPHICS_SUCCESS );
	assert( nTextureBytes == 256ULL * 256 * 4 );
	texture.nMipLevels = 9;
	assert( sirD3D9EstimateTextureBytes( &texture, &nTextureBytes ) == SIR_GRAPHICS_SUCCESS );
	assert( nTextureBytes == 349524 );
	texture.nMipLevels = 10;
	assert( sirD3D9EstimateTextureBytes( &texture, &nTextureBytes ) == SIR_GRAPHICS_INVALID_ARGUMENT );
	texture.nMipLevels = 1;
	texture.nWidth = 8;
	texture.nHeight = 8;
	texture.eFormat = SIR_GRAPHICS_FORMAT_BC1_UNORM;
	assert( sirD3D9EstimateTextureBytes( &texture, &nTextureBytes ) == SIR_GRAPHICS_SUCCESS && nTextureBytes == 32 );
	texture.eFormat = SIR_GRAPHICS_FORMAT_BC3_UNORM;
	assert( sirD3D9EstimateTextureBytes( &texture, &nTextureBytes ) == SIR_GRAPHICS_SUCCESS && nTextureBytes == 64 );
	texture.nUsage |= SIR_GRAPHICS_USAGE_COLOR_ATTACHMENT;
	assert( sirD3D9EstimateTextureBytes( &texture, &nTextureBytes ) == SIR_GRAPHICS_UNSUPPORTED );
	texture.eFormat = SIR_GRAPHICS_FORMAT_BGRA8_UNORM;
	assert( sirD3D9EstimateTextureBytes( &texture, &nTextureBytes ) == SIR_GRAPHICS_SUCCESS && nTextureBytes == 256 );
	assert( sirD3D9EstimateTextureBytes( &texture, nullptr ) == SIR_GRAPHICS_INVALID_ARGUMENT );
	sirGraphicsABIFixedStage_t stages[2] = {};
	stages[0].nTextureUnit = 0;
	stages[1].nTextureUnit = 1;
	sirGraphicsABIFixedRecipe_t recipe = {};
	recipe.nSize = sizeof( recipe );
	recipe.nTextureStageCount = 2;
	recipe.pStages = stages;
	recipe.nAlphaCompare = SIR_GRAPHICS_COMPARE_ALWAYS;
	assert( sirD3D9ValidateFixedRecipe( &recipe, 2, 2, 8 ) == SIR_GRAPHICS_SUCCESS );
	assert( sirD3D9ValidateFixedRecipe( &recipe, 1, 2, 8 ) == SIR_GRAPHICS_UNSUPPORTED );
	stages[1].nTextureUnit = 0;
	assert( sirD3D9ValidateFixedRecipe( &recipe, 2, 2, 8 ) == SIR_GRAPHICS_UNSUPPORTED );
	stages[1].nTextureUnit = 1;
	stages[0].nColorOperation = 999;
	assert( sirD3D9ValidateFixedRecipe( &recipe, 2, 2, 8 ) == SIR_GRAPHICS_UNSUPPORTED );
	stages[0].nColorOperation = SIR_GRAPHICS_FIXED_OP_INTERPOLATE;
	assert( sirD3D9ValidateFixedRecipe( &recipe, 2, 2, 8 ) == SIR_GRAPHICS_UNSUPPORTED );
	stages[0].nColorOperation = SIR_GRAPHICS_FIXED_OP_MODULATE;
	recipe.fAlphaReference = -1.0f;
	assert( sirD3D9ValidateFixedRecipe( &recipe, 2, 2, 8 ) == SIR_GRAPHICS_UNSUPPORTED );
	recipe.fAlphaReference = 0.5f;
	recipe.nLightCount = 1;
	assert( sirD3D9ValidateFixedRecipe( &recipe, 2, 2, 8 ) == SIR_GRAPHICS_INVALID_ARGUMENT );
	sirGraphicsABIFixedLight_t light = {};
	recipe.pLights = &light;
	recipe.nFogMode = SIR_GRAPHICS_FIXED_FOG_LINEAR;
	recipe.fFogStart = 20.0f;
	recipe.fFogEnd = 10.0f;
	assert( sirD3D9ValidateFixedRecipe( &recipe, 2, 2, 8 ) == SIR_GRAPHICS_UNSUPPORTED );
	recipe.fFogEnd = 30.0f;
	recipe.fFogDensity = -1.0f;
	assert( sirD3D9ValidateFixedRecipe( &recipe, 2, 2, 8 ) == SIR_GRAPHICS_UNSUPPORTED );
	recipe.fFogDensity = 1.0f;
	assert( sirD3D9ValidateFixedRecipe( &recipe, 2, 2, 0 ) == SIR_GRAPHICS_UNSUPPORTED );
	assert( sirD3D9ValidateFixedRecipe( &recipe, 2, 2, 8 ) == SIR_GRAPHICS_SUCCESS );
	assert( sirD3D9ValidateDrawRange( SIR_GRAPHICS_TOPOLOGY_TRIANGLES, 4, 1, 13 ) == SIR_GRAPHICS_SUCCESS );
	assert( sirD3D9ValidateDrawRange( SIR_GRAPHICS_TOPOLOGY_TRIANGLES, 4, 2, 13 ) == SIR_GRAPHICS_INVALID_ARGUMENT );
	assert( sirD3D9ValidateDrawRange( SIR_GRAPHICS_TOPOLOGY_TRIANGLES, UINT32_MAX, 0, UINT32_MAX ) == SIR_GRAPHICS_INVALID_ARGUMENT );
	assert( sirD3D9ValidateDrawRange( SIR_GRAPHICS_TOPOLOGY_LINES, 2, 3, 7 ) == SIR_GRAPHICS_SUCCESS );
	assert( sirD3D9ValidateDrawRange( SIR_GRAPHICS_TOPOLOGY_LINE_STRIP, 2, 3, 5 ) == SIR_GRAPHICS_INVALID_ARGUMENT );
	assert( sirD3D9ValidateDrawRange( SIR_GRAPHICS_TOPOLOGY_TRIANGLE_STRIP, 2, 0, 4 ) == SIR_GRAPHICS_SUCCESS );
	assert( sirD3D9ValidateDrawRange( SIR_GRAPHICS_TOPOLOGY_POINTS, 1, 0, 1 ) == SIR_GRAPHICS_SUCCESS );
	assert( sirD3D9ValidateDrawRange( SIR_GRAPHICS_TOPOLOGY_TRIANGLES, 0, 0, 10 ) == SIR_GRAPHICS_INVALID_ARGUMENT );
	assert( sirD3D9ValidateDrawRange( SIR_GRAPHICS_TOPOLOGY_PATCHES, 1, 0, 10 ) == SIR_GRAPHICS_UNSUPPORTED );
	sirD3D9TextureUploadLayout_t upload = {};
	upload.eFormat = SIR_GRAPHICS_FORMAT_RGBA8_UNORM;
	upload.nWidth = 7;
	upload.nHeight = 3;
	upload.nRowPitch = 32;
	upload.nBytes = 92;
	uint32_t nRowBytes = 0;
	uint32_t nRows = 0;
	assert( sirD3D9ValidateTextureUploadLayout( &upload, &nRowBytes, &nRows ) == SIR_GRAPHICS_SUCCESS );
	assert( nRowBytes == 28 && nRows == 3 );
	upload.nBytes = 91;
	assert( sirD3D9ValidateTextureUploadLayout( &upload, &nRowBytes, &nRows ) == SIR_GRAPHICS_INVALID_ARGUMENT );
	upload.nBytes = 92;
	upload.nRowPitch = 27;
	assert( sirD3D9ValidateTextureUploadLayout( &upload, &nRowBytes, &nRows ) == SIR_GRAPHICS_INVALID_ARGUMENT );
	upload.eFormat = SIR_GRAPHICS_FORMAT_BC3_UNORM;
	upload.nWidth = 5;
	upload.nHeight = 5;
	upload.nRowPitch = 32;
	upload.nBytes = 64;
	assert( sirD3D9ValidateTextureUploadLayout( &upload, &nRowBytes, &nRows ) == SIR_GRAPHICS_SUCCESS );
	assert( nRowBytes == 32 && nRows == 2 );
	upload.eFormat = SIR_GRAPHICS_FORMAT_BC7_UNORM;
	assert( sirD3D9ValidateTextureUploadLayout( &upload, &nRowBytes, &nRows ) == SIR_GRAPHICS_UNSUPPORTED );
	texture.nWidth = 16;
	texture.nHeight = 8;
	texture.nDepth = 4;
	texture.nArrayLayers = 1;
	texture.nMipLevels = 3;
	texture.nUsage = SIR_GRAPHICS_USAGE_SAMPLED;
	texture.eDimension = SIR_GRAPHICS_TEXTURE_3D;
	texture.eFormat = SIR_GRAPHICS_FORMAT_BGRA8_UNORM;
	assert( sirD3D9EstimateTextureBytes( &texture, &nTextureBytes ) == SIR_GRAPHICS_SUCCESS &&
	        nTextureBytes == ( 16 * 8 * 4 + 8 * 4 * 2 + 4 * 2 ) * 4 );
	texture.eFormat = SIR_GRAPHICS_FORMAT_BC1_UNORM;
	assert( sirD3D9ValidateTexture( &texture, 64, 1 ) == SIR_GRAPHICS_UNSUPPORTED );
	texture.eDimension = SIR_GRAPHICS_TEXTURE_CUBE;
	texture.nDepth = 1;
	texture.nArrayLayers = 6;
	texture.nHeight = 16;
	texture.eFormat = SIR_GRAPHICS_FORMAT_BC1_UNORM;
	assert( sirD3D9EstimateTextureBytes( &texture, &nTextureBytes ) == SIR_GRAPHICS_SUCCESS &&
	        nTextureBytes == ( 4 * 4 + 2 * 2 + 1 ) * 8 * 6 );
	texture.nArrayLayers = 12;
	assert( sirD3D9ValidateTexture( &texture, 64, 1 ) == SIR_GRAPHICS_INVALID_ARGUMENT );
	texture.nArrayLayers = 6;
	texture.nWidth = UINT32_MAX;
	texture.nHeight = UINT32_MAX;
	texture.nMipLevels = 1;
	assert( sirD3D9EstimateTextureBytes( &texture, &nTextureBytes ) == SIR_GRAPHICS_CAPACITY_EXCEEDED );
	sirGraphicsSamplerDesc_t sampler = {};
	sampler.eFilter = SIR_GRAPHICS_FILTER_LINEAR;
	sampler.eAddressU = SIR_GRAPHICS_ADDRESS_CLAMP;
	sampler.eAddressV = SIR_GRAPHICS_ADDRESS_REPEAT;
	sampler.eAddressW = SIR_GRAPHICS_ADDRESS_MIRROR;
	sampler.fMaximumAnisotropy = 1.0f;
	assert( sirD3D9ValidateSampler( &sampler, 8 ) == SIR_GRAPHICS_SUCCESS );
	sampler.eFilter = SIR_GRAPHICS_FILTER_ANISOTROPIC;
	sampler.fMaximumAnisotropy = 4.0f;
	assert( sirD3D9ValidateSampler( &sampler, 8 ) == SIR_GRAPHICS_SUCCESS );
	assert( sirD3D9ValidateSampler( &sampler, 2 ) == SIR_GRAPHICS_UNSUPPORTED );
	sampler.fMaximumAnisotropy = 1.0f;
	sampler.fMinimumLod = 1.0f;
	assert( sirD3D9ValidateSampler( &sampler, 8 ) == SIR_GRAPHICS_UNSUPPORTED );
	sampler.fMinimumLod = 0.0f;
	sampler.eAddressV = ( sirGraphicsAddressMode_t )255;
	assert( sirD3D9ValidateSampler( &sampler, 8 ) == SIR_GRAPHICS_UNSUPPORTED );
	sampler.eAddressV = SIR_GRAPHICS_ADDRESS_REPEAT;
	sampler.eFilter = SIR_GRAPHICS_FILTER_LINEAR;
	sampler.fMaximumAnisotropy = 0.0f;
	assert( sirD3D9ValidateSampler( &sampler, 8 ) == SIR_GRAPHICS_UNSUPPORTED );
	assert( sirD3D9ValidateSampler( nullptr, 8 ) == SIR_GRAPHICS_INVALID_ARGUMENT );
	assert( sirD3D9ValidateSampler( &sampler, 0 ) == SIR_GRAPHICS_INVALID_ARGUMENT );
	return 0;
}
